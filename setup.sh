#!/usr/bin/env bash
# Bootstrap the EvoGraph-Quant dev environment.
# Usage:  ./setup.sh            (uses python3.12 / 3.11 / 3.10 / python3, first found)
#         PYTHON=python3.13 ./setup.sh
set -euo pipefail
cd "$(dirname "$0")"

PY="${PYTHON:-}"
if [ -z "$PY" ]; then
  for c in python3.12 python3.11 python3.13 python3.10 python3; do
    command -v "$c" >/dev/null 2>&1 && { PY="$c"; break; }
  done
fi
echo ">> Using $($PY --version) ($PY)"

# Recreate .venv if it was built with a different Python version
if [ -d .venv ]; then
  want="$($PY -c 'import sys;print(f"{sys.version_info[0]}.{sys.version_info[1]}")')"
  have="$(.venv/bin/python -c 'import sys;print(f"{sys.version_info[0]}.{sys.version_info[1]}")' 2>/dev/null || echo none)"
  if [ "$want" != "$have" ]; then
    echo ">> .venv is Python $have, rebuilding for $want"
    rm -rf .venv
  fi
fi
[ -d .venv ] || "$PY" -m venv .venv

.venv/bin/python -m pip install -q --upgrade pip

# Same Python version as the lock -> exact pins; otherwise resolve fresh and re-lock.
lock_py="$(head -1 requirements.lock.txt 2>/dev/null | sed -n 's/^# python \([0-9.]*\).*/\1/p')"
cur_py="$(.venv/bin/python -c 'import sys;print(f"{sys.version_info[0]}.{sys.version_info[1]}")')"
if [ -f requirements.lock.txt ] && [ "$lock_py" = "$cur_py" ]; then
  echo ">> Installing exact pins from requirements.lock.txt (Python $cur_py)"
  .venv/bin/pip install -q -r requirements.lock.txt
else
  echo ">> Lock is for Python ${lock_py:-unknown}; resolving requirements.txt and re-locking for $cur_py"
  .venv/bin/pip install -q -r requirements.txt
  { echo "# python $cur_py — generated by setup.sh, do not edit"; .venv/bin/pip freeze; } > requirements.lock.txt
fi

[ -f .env ] || { [ -f .env.example ] && cp .env.example .env && echo ">> Created .env from .env.example — fill in your keys"; }

echo ">> Import check"
.venv/bin/python - <<'EOF'
import warnings; warnings.filterwarnings("ignore")
from daytona import Daytona, DaytonaConfig, CreateSandboxFromSnapshotParams
from adalflow.optim.parameter import Parameter
import neo4j, openai, streamlit, streamlit_agraph, dotenv, pydantic
print("   all imports OK")
EOF
echo ">> Done. Activate with:  source .venv/bin/activate"
